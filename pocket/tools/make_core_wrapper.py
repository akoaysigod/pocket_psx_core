# Generates pocket/src/fpga/core/psx_pocket_core.vhd: rtl/psx_mister.vhd with every MiSTer-only option tied
# to its Pocket value. usage: python3 pocket/tools/make_core_wrapper.py rtl/psx_mister.vhd pocket/src/fpga/core/psx_pocket_core.vhd
import re, sys
src = open(sys.argv[1]).read()
ent = re.search(r'entity psx_mister is.*?port\s*\((.*?)\);\s*end entity', src, re.S).group(1)
ports = []
for line in ent.split('\n'):
    line = line.split('--')[0].strip().rstrip(';').strip()
    m = re.match(r'(\w+)\s*:\s*(in|out)\s+(.+?)(\s*:=.*)?$', line)
    if m:
        ports.append((m.group(1), m.group(2), m.group(3).strip()))

# inputs tied to a constant (feature off / SotN setting)
TIE = {
 'loadExe': "'0'", 'exe_initial_pc': '(others => \'0\')', 'exe_initial_gp': '(others => \'0\')',
 'exe_load_address': '(others => \'0\')', 'exe_file_size': '(others => \'0\')', 'exe_stackpointer': '(others => \'0\')',
 'ram8mb': "'0'", 'TURBO_MEM': "'0'", 'TURBO_COMP': "'0'", 'TURBO_CACHE': "'0'", 'TURBO_CACHE50': "'0'",
 'REPRODUCIBLEGPUTIMING': "'0'", 'INSTANTSEEK': "'0'", 'FORCECDSPEED': '"000"', 'LIMITREADSPEED': "'0'",
 'IGNORECDDMATIMING': "'0'", 'ditherOff': "'0'", 'interlaced480pHack': "'0'", 'showGunCrosshairs': "'0'",
 'enableNeGconRumble': "'0'", 'fpscountOn': "'0'", 'cdslowOn': "'0'", 'testSeek': "'0'", 'pauseOnCDSlow': "'0'",
 'errorOn': "'0'", 'LBAOn': "'0'", 'PATCHSERIAL': "'0'", 'noTexture': "'0'", 'textureFilter': '"00"',
 'textureFilterStrength': '"00"', 'textureFilter2DOff': "'0'", 'dither24': "'0'", 'render24': "'0'",
 'drawSlow': "'0'", 'syncVideoOut': "'0'", 'syncInterlace': "'0'", 'rotate180': "'0'", 'fixedVBlank': "'0'",
 'vCrop': '"00"', 'hCrop': "'0'", 'SPUon': "'1'", 'SPUIRQTrigger': "'0'", 'SPUSDRAM': "'1'", 'REVERBOFF': "'0'",
 'REPRODUCIBLESPUDMA': "'0'", 'WIDESCREEN': '"00"', 'oldGPU': "'0'", 'biosregion': '"00"', 'region': '"00"',
 'isPal': "'0'", 'pal60': "'0'",
 # Pocket: no Linux side / no lid / no OSD pause / disc always present
 'pause': "'0'", 'hps_busy': "'0'", 'LIDopen': "'0'", 'fastCD': "'0'", 'videoout_on': "'1'", 'fastboot': "'0'",
 'memcard2_load': "'0'", 'memcard2_mounted': "'0'", 'memcard2_available': "'0'", 'memcard2_ack': "'0'",
 'memcard2_write': "'0'", 'memcard2_addr': '(others => \'0\')', 'memcard2_dataIn': '(others => \'0\')',
 'DSAltSwitchMode': "'0'", 'PadPortEnable1': "'1'", 'PadPortDigital1': "'1'",
 'multitap': "'0'", 'multitapDigital': "'0'", 'multitapAnalog': "'0'", 'MouseEvent': "'0'", 'MouseLeft': "'0'",
 'MouseRight': "'0'", 'MouseX': '(others => \'0\')', 'MouseY': '(others => \'0\')', 'ToggleDS': '"0000"',
 'snacPort1': "'0'", 'snacPort2': "'0'", 'irq10Snac': "'0'", 'actionNextSnac': "'0'", 'receiveValidSnac': "'0'",
 'ackSnac': "'0'", 'snacMC': "'0'", 'receiveBufferSnac': '(others => \'0\')',
 'increaseSSHeaderCount': "'0'", 'save_state': "'0'", 'load_state': "'0'", 'savestate_number': '0',
 'rewind_on': "'0'", 'rewind_active': "'0'", 'cheat_clear': "'0'", 'cheats_enabled': "'0'", 'cheat_on': "'0'",
 'cheat_in': '(others => \'0\')', 'Cheats_BusReadData': '(others => \'0\')', 'Cheats_BusDone': "'0'",
}
for p in ('Mouse', 'GunCon', 'neGcon', 'Wheel', 'DS', 'Justif', 'Stick', 'Popn', 'Analog'):
    TIE['PadPort%s1' % p] = "'0'"
for p in ('Enable', 'Digital', 'Analog', 'Mouse', 'GunCon', 'neGcon', 'Wheel', 'DS', 'Justif', 'Stick', 'Popn'):
    TIE['PadPort%s2' % p] = "'0'"
for n in ('1X', '1Y', '2X', '2Y'):
    for pl in '1234':
        TIE['Analog%sP%s' % (n, pl)] = '(others => \'0\')'
KEYS = [n for n, d, t in ports if n.startswith('Key')]   # player 1 only: bit 0 live
# outputs of cut features: left open
OPEN = re.compile(r'^(Rumble|memcard2_|Cheats_|cheats_active|validSStates|state_loaded|transmitValueSnac|selected|clk9Snac|beginTransferSnac|cd_hps_lba_sim|padMode|region_out|DisplayWidth|DisplayHeight|DisplayOffsetX|DisplayOffsetY|video_fbmode|video_fb24|video_frameindex|video_isPal)')  # Pocket: MiSTer scaler/framebuffer-only outputs left open

for n, d, t in ports:
    if d == 'in' and n not in TIE and n not in KEYS:
        pass
wport, maps = [], []
for n, d, t in ports:
    if d == 'in' and n in TIE:
        maps.append('%s => %s' % (n, TIE[n]))
    elif n in KEYS:
        wport.append('%s : in std_logic' % n)
        maps.append('%s => "000" & %s' % (n, n))
    elif d == 'out' and OPEN.match(n):
        maps.append('%s => open' % n)
    else:
        wport.append('%s : %s %s' % (n, d, t))
        maps.append('%s => %s' % (n, n))
out = ['library IEEE;', 'use IEEE.std_logic_1164.all;', 'use IEEE.numeric_std.all;', '',
       '-- GENERATED by pocket/tools/make_core_wrapper.py from rtl/psx_mister.vhd - do not edit.',
       '-- psx_mister with all MiSTer-only options tied off for the Analogue Pocket build.',
       'entity psx_pocket_core is', '   port', '   (']
out.append(';\n'.join('      ' + p for p in wport))
out += ['   );', 'end entity;', '', 'architecture arch of psx_pocket_core is', 'begin', '   ipsx : entity work.psx_mister',
        '   port map', '   (']
out.append(',\n'.join('      ' + m for m in maps))
out += ['   );', 'end architecture;']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('ports', len(ports), 'tied', sum(1 for n,d,t in ports if d=='in' and n in TIE), 'open', sum(1 for n,d,t in ports if d=='out' and OPEN.match(n)), 'live', len(wport))
missing = [k for k in TIE if k not in [p[0] for p in ports]]
print('unknown tie names:', missing)
