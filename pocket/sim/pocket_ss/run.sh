#!/bin/sh
# pocket_psx save states (see tb_pocket_ss.vhd): APF's save / load commands, the bridge window (SDRAM parts through
# the loader FIFO and the save-state reader on channel 3, VRAM through pocket_memcard and the PSRAM models) and the
# core's reset / pause / restore sequence. The PSX core is replaced by a stub (generated here from the wrapper's
# entity) that plays the save-state routine's part of the handshake.
# usage: ALTERA_MF_DIR=<compiled altera_mf dir> [WORKDIR=<dir>] pocket/sim/pocket_ss/run.sh
set -e
here=$(cd "$(dirname "$0")" && pwd)
core="$here/../../src/fpga/core"
work="${WORKDIR:-$here/work}"; mkdir -p "$work"; cd "$work"

python3 - "$core/psx_pocket_core.vhd" core_stub.vhd <<'EOF'
import re, sys
src = open(sys.argv[1]).read()
ent = re.search(r'entity psx_pocket_core is.*?end entity;', src, re.S).group(0)
outs = re.findall(r'^\s*(\w+)\s*:\s*out\s+([^;\n]+?)\s*;?\s*$', ent, re.M)
own = {'isPaused', 'ss_cmd', 'ss_cmd_we'}
drive = []
for n, t in outs:
    if n in own:
        continue
    drive.append('   %s <= %s;' % (n, "(others => '0')" if 'vector' in t else "'0'"))
stub = '''-- GENERATED by pocket/sim/pocket_ss/run.sh: psx_pocket_core stub for tb_pocket_ss. Idle outputs; the save-state
-- routine's part of the handshake with pocket_psx (ss_req -> enter -> captured -> paused while pause -> done after the
-- release; restore boot -> done).
library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;
%s

architecture stub of psx_pocket_core is
   signal st : integer := 0;
begin
%s

   process (clk1x)
      variable n : integer := 0;
   begin
      if rising_edge(clk1x) then
         ss_cmd_we <= '0';
         if (reset = '1') then
            isPaused <= '0';
            n        := 0;
            st       <= 0;
            if (ss_restore = '1') then st <= 10; end if;
         else
            n := n + 1;
            case (st) is
               when 0 =>                                     -- game running
                  n := 0;
                  if (ss_req = '1') then st <= 1; end if;
               when 1 =>                                     -- hidden interrupt taken: entered
                  if (n = 300) then
                     report "stub: routine entered (save)";
                     ss_cmd <= x"01"; ss_cmd_we <= '1'; st <= 2; n := 0;
                  end if;
               when 2 =>                                     -- collecting
                  if (n = 1000) then
                     report "stub: captured";
                     ss_cmd <= x"02"; ss_cmd_we <= '1'; st <= 3; n := 0;
                  end if;
               when 3 =>                                     -- spinning; the core pauses at an idle point
                  if (pause = '0') then
                     n := 0;
                  elsif (n = 40) then
                     report "stub: paused";
                     isPaused <= '1'; st <= 4;
                  end if;
               when 4 =>
                  if (pause = '0') then
                     report "stub: unpaused";
                     isPaused <= '0'; st <= 5; n := 0;
                  end if;
               when 5 =>                                     -- released: put back, return into the game
                  if (n = 200) then
                     assert ss_status(1) = '1' report "stub: unpaused but not released" severity error;
                     report "stub: done (save)";
                     ss_cmd <= x"03"; ss_cmd_we <= '1'; st <= 0;
                  end if;
               when 10 =>                                    -- restore boot
                  if (n = 500) then
                     assert ss_status(0) = '1' report "stub: restore boot without ss_restore in the status" severity error;
                     report "stub: done (restore)";
                     ss_cmd <= x"03"; ss_cmd_we <= '1'; st <= 0;
                  end if;
               when others => null;
            end case;
         end if;
      end if;
   end process;
end architecture;
''' % (ent, '\n'.join(drive))
open(sys.argv[2], 'w').write(stub)
EOF

# vram_psram on clk2x without vram_cdc (VRAM_CLK3X false): the PSRAM models answer the clk3x / vram_cdc path's aux
# reads with 'Z' in simulation (pocket/sim/pocket_memcard CDC=true fails the same way on main 1d2a8b6)
sed 's/constant VRAM_CLK3X   : boolean := true;/constant VRAM_CLK3X   : boolean := false;/' "$core/pocket_psx.vhd" > pocket_psx.vhd
grep -q "VRAM_CLK3X   : boolean := false" pocket_psx.vhd

L="-L . -L ${ALTERA_MF_DIR:-.}"
rtl="$here/../../../rtl"
nvc --std=2008 $L --work=mem -a --relaxed "$rtl/RamMLAB.vhd"
nvc --std=2008 $L -a --relaxed "$core/psram_async.vhd" "$core/vram_psram.vhd" "$core/vram_cdc.vhd" "$core/pocket_memcard.vhd" \
   "$core/pocket_cd.vhd" "$core/pocket_buttons.vhd" "$core/pocket_video.vhd" "$core/pocket_audio48.vhd" "$core/pocket_diag.vhd" \
   core_stub.vhd pocket_psx.vhd "$here/../vram_psram/psram_model.vhd" "$here/tb_pocket_ss.vhd"
nvc --std=2008 --ieee-warnings=off $L -H 1g -e tb_pocket_ss -r
